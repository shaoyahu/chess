/**
 * **「房间邀请 + 分享」门禁（`scripts/verify-invite.ts`）的分组表。**
 *
 * 分组原则见 `scripts/lib/gate-groups.ts`。这一套的门禁编号是 `I1`~`I7`。
 *
 * ## 为什么按「机制」分
 *
 * 这一套里有**三个互不相干**的机制，坏在哪儿都长得不一样：
 *
 * - `invite`：**邀请从发到收** —— 私聊面板里那枚按钮在不在、
 *   对方收到的是不是**可点的卡片**、点一下能不能**直接进房**。
 * - `share`：**分享** —— 顶栏那枚分享按钮、菜单里有没有那两件事、
 *   复制出来的**链接对不对**（读剪贴板核对，不看提示就算过）。
 * - `join`：**进房的两条岔路** —— 已在别的局里点邀请要不要先确认
 *   （离开 = 判负，代价必须摆在眼前）；没记住用户名的人打开分享链接
 *   能不能取个名**直接落到房间里**。
 */
import type { GroupTable } from './gate-groups';

export const INVITE_GROUPS: GroupTable = {
  /** 邀请这条链：按钮 → 可点卡片 → 点一下直接进房 */
  invite: ['I1', 'I2', 'I3'],
  /** 分享：菜单两项 + 剪贴板里的链接要对 */
  share: ['I5', 'I6'],
  /** 进房的两条岔路：跨房间要二次确认、新访客取名直接进 */
  join: ['I4', 'I7'],
};
