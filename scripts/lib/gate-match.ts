/**
 * 「门禁红了没有」的判定 —— 变异脚本靠它判断某条变异是否被门禁抓到。
 *
 * 判定规则只有一条，但**两个方向都出过事故**，所以写在这里并配单测：
 *
 * 1. 编号要**紧跟在「❌ 」后面**：门禁的红行格式永远是
 *    `❌ <编号> <说明> —— <细节>`（编号是第一个词），所以只认这个位置 ——
 *    拿 `includes('U2')` 满行去找，会被「❌ U20 …」**冒充**成抓到（假绿）。
 * 2. 编号后面**可以跟字母、不能跟数字**：U9a / U9b 是**同一条判据的子编号**，
 *    期望 `U9` 的变异必须能认出它们（漏掉就成了假阴性：明明抓到了却说没抓到）。
 *
 * 规则写成 `❌\s*<编号>(?![0-9])` 正好两条都满足。
 */

/**
 * 输出里有没有「期望编号」的红行。
 *
 * @param output 门禁脚本的完整输出
 * @param expect 期望变红的门禁编号（如 `U9`）
 */
export function gateTurnedRed(output: string, expect: string): boolean {
  const re = new RegExp(`❌\\s*${expect}(?![0-9])`);
  return output.split('\n').some((line) => re.test(line));
}
