/**
 * **「私信」门禁（`scripts/verify-dm.ts`）的分组表。**
 *
 * 分组原则见 `scripts/lib/gate-groups.ts`。这一套的门禁编号是 `D1`~`D14`。
 *
 * ## 为什么按「机制」分
 *
 * 私信这条链路上有五个**互不相干**的机制，坏在哪儿都长得不一样：
 *
 * - `list`：**在大厅里找到一个人** —— 顶栏「在线 N」点开是真人名单，
 *   左键某人直接进私信、右键某人弹菜单，两条路都落在**那个人**身上；
 *   名单浮层**点别处就收起**（它 z-index 高过私信抽屉，不收就盖着聊天窗）。
 * - `message`：**消息真的来回** —— 发出去对方收得到、自己也留一份；
 *   对方发来有未读角标和提示，打开面板角标清零、历史还在；
 *   连点有**最小发送间隔**（不然对面会被糊成一列提示）。
 * - `topbar`：**顶栏入口本身** —— 图标按钮的点击区够大（用户说「设置图标太小」）、
 *   收信弹的 toast 不许盖住顶栏按钮、私信入口是**聊天气泡**而不是信封、
 *   提示区**限位右上角**（条数封顶 + 同一个人合并成一条）。
 * - `room`：**对局页也有这一套** —— 人在棋盘上也要能看见在线的人。
 * - `copy`：**页面上不靠说明文字** —— 说明一旦写在界面上，界面就等于没设计好。
 *
 * ## 组内顺序
 *
 * - `list` 组里 `D1` 必须先跑（它把在线名单打开），`D2` / `D9` 都在这份名单上操作。
 * - `message` 组里 `D3` 必须先跑（它把「对话对象」定下来），
 *   `D4` 才能在**同一条会话**上验未读和历史。
 * - `topbar` 组里 `D6`（toast 不盖顶栏）要先跑 —— 它要在**大厅**里触发一条提示；
 *   `D7` 再整页跳到对局页。
 * - 每条门禁都**自带前置准备**（自己开名单、自己跳页面），
 *   单跑任何一组都不会因为「上一条没跑」而假红。
 */
