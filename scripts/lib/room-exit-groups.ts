/**
 * **「离开房间」门禁（`scripts/verify-room-exit.ts`）的分组表。**
 *
 * 分组原则见 `scripts/lib/gate-groups.ts`。这一套的门禁编号是 `X1`~`X3`。
 *
 * ## 为什么按「角色」分
 *
 * 「离开房间」这条机制对**棋手**和**观战者**是两套规则：
 *
 * - 棋手在对局中离开 = 判负 → 必须二次确认；
 * - 观战者离开不影响对局 → 没有要确认的理由，直接走人。
 *
 * 两条规则共享同一个按钮，但**判据完全不同**（服务端是否收座位、
 * 是否弹确认、观战名单是否清空），所以分成两组。
 *
 * ## 组内顺序
 *
 * - `player` 组里 `X1` 必须先跑（它离开之后，`X2` 才能在**同一段报文流水**里
 *   找到那一条 `room.leave`）。
 */
import type { GroupTable } from './gate-groups';

export const ROOM_EXIT_GROUPS: GroupTable = {
  /** 棋手离开：二次确认 → 服务端收座位 → 离开后不再自动回房间 */
  player: ['X1', 'X2'],
  /** 观战者离开：不弹确认，直接走人，服务端清观战名单 */
  spectator: ['X3'],
};
