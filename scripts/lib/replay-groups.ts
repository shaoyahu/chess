/**
 * **「复盘」门禁（`scripts/verify-replay.ts`）的分组表。**
 *
 * 分组原则见 `scripts/lib/gate-groups.ts`。这一套的门禁编号是 `R1`~`R11`。
 *
 * ## 为什么按「机制」分两组
 *
 * - `layout` —— **终局提示的位置**：结果卡浮在棋盘上、且**不挪动任何东西**。
 *   这一组跟复盘本身无关（它验的是「将死提示别把页面顶歪」），
 *   所以单独一组，变异时只跑这一组（快）。
 * - `replay` —— **复盘功能本身**：按钮、控制器、沿棋谱步进、还原、
 *   自由走棋、各看各的、再来一局后自动退出。
 *
 * ## 组内顺序
 *
 * `replay` 组是**一条有状态链**，必须按脚本里的先后顺序跑：
 *   R2（双方都有按钮）→ R3（点开有控制器）→ R4（步进）→ R5（还原回开局）
 *   → R6（自由走棋）→ R7（还原回自由走棋之前）→ R8（不发服务端）→ R9（各看各的）
 *   → R10（窄屏不挤没棋盘）→ R11（再来一局后复盘退出）。
 * 中间任何一步失败，后面的判据就建立在错的前提上。
 *
 * R11 放最后：它会**开新的一局**，把房间状态整个换掉 ——
 * 放中间的话，后面的判据就跑在新局上了。
 */
import type { GroupTable } from './gate-groups';

export const REPLAY_GROUPS: GroupTable = {
  /** 终局提示浮在棋盘上，不挪动页面里的其他东西 */
  layout: ['R1'],
  /**
   * 复盘：按钮 / 控制器 / 步进 / 还原 / 自由走棋 / 不发服务端 / 各看各的 /
   * 窄屏不挤没棋盘 / 再来一局后自动退出
   */
  replay: ['R2', 'R3', 'R4', 'R5', 'R6', 'R7', 'R8', 'R9', 'R10', 'R11'],
};
