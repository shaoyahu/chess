/**
 * 门禁分组 —— 「超时判负但不终局」这一套机制。
 *
 * 分组表、门禁编号、组的定义**只能有一处**（见 `lib/gate-groups.ts` 的说明）。
 */

/**
 * `timeout` 组：超时判负这条规则的**全部**门禁。
 *
 * 为什么都放一组：
 *   T1~T3 断的是同一件事（界面上「超时」这件事有没有被说出来），
 *   T4~T6 断的是另一件事（判负之后这局还能不能继续）。
 *   两者共享同一个准备步骤（造一个已经超时的房间），拆开跑反而更慢。
 */
export const TIMEOUT_GROUPS: Record<string, string[]> = {
  timeout: ['T1', 'T2', 'T3', 'T4', 'T5', 'T6', 'T7'],
};
