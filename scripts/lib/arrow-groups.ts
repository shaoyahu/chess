/**
 * **走子箭头门禁（`scripts/verify-move-arrow.ts`）的分组表。**
 *
 * 分组原则见 `scripts/lib/gate-groups.ts`。这一套的门禁编号是 `G1`~`G30`（41 条）。
 *
 * ## 为什么 arrow 这套的分组比 ui-style 难
 *
 * arrow 脚本是一个**线性状态机**，不是一堆互不相干的断言：
 *
 * - 它会**反复改视口**（宽屏 → 900×1200 → 430×932 → 1000×1000 → 900×700 → 恢复）；
 * - 它会**切换 2D / 3D**；
 * - 它会**建房间、拉对手、改对局状态**（求和 / 悔棋 / 认输 / 再来一局）。
 *
 * 所以「跳过一条门禁」不等于「少测一件事」—— 如果被跳过的块里**带着视口切换**
 * 或者**带着状态变更**，后面所有块测到的页面状态就全变了，门禁会**假红**。
 *
 * ## 两条硬规矩（改这个脚本之前先读）
 *
 * **① 共享的测量与准备代码必须「总是执行」，不许关进门禁块里。**
 *
 * 脚本里被多个块共用的东西都已经从块里**提出来了**，放在块外面：
 *
 * | 提出来的东西            | 原来在哪个块里 | 现在在哪 |
 * |------------------------|----------------|----------|
 * | `layoutWide` 测量       | G18 块         | G18 块之前 |
 * | 900×1200 视口 + `layoutNarrow` | G3 块  | G3 块之后、G4 块之前 |
 * | 430×932 视口            | G19 块         | G19 块之前 |
 * | 1000×1000 视口          | G12 块         | G12 块之前 |
 * | 900×700 视口 + `layoutTall` | G13 块     | G13 块之前 |
 * | 清视口 + 切 3D + `canvasBox` | G11 块    | G11 块之后、G5 块之前 |
 * | 切回 2D + 建对手房间     | G10 块         | G10 块之后、G22 块之前 |
 *
 * 顺序与原来**完全一致** —— 提出来的只是「搬到哪里」，不是「什么时候跑」。
 * 少了这一步，跳过一个组就会连带把视口带偏，后面每一条门禁都会假红。
 *
 * **② 一个块里的断言必须整体启用。**
 *
 * 所以包裹块的 `gateEnabledAny([...])` 里列的是**这个块里实际断言的全部门禁**，
 * 不只是块名。比如 G18 块里同时断言了 G18 和 G2，就写成 `["G18", "G2"]` ——
 * 这样「选 chat 组会跑到 G2 的断言」「选 arrow3d 组会跑到 G18 的断言」，
 * 两条都不会漏守。
 *
 * ## 顺序依赖：哪些门禁必须在同一组
 *
 * 脚本里的先后顺序是**语义的一部分**，跳组时必须整组跳：
 *
 * - `G16`（打开聊天弹层）→ `G17`（收起弹层）
 * - `G23`（认输 → 对局结束）→ `G29`（再来一局按钮才出现）→ `G29d`（双方申请 → 开新局）
 * - `G28b`（我方发起悔棋，造料）→ `G25c`（断言对手真的收到了）
 * - `G27`（我方求和 → 浮层）→ `G24`（对方求和 → 浮层）
 *
 * 所以 `endgame` 组把「认输」和「再来一局」放在一起 —— 少了前者，
 * 后者测的根本不是同一件事。
 */
