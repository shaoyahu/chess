/**
 * **残局关卡的数据形状** —— 一关就是「一个局面 + 一条解法线」。
 *
 * ## 为什么关卡和课程是两套东西
 *
 * `lessons/` 里的课程是**讲解**：一条演示线，每手配一句话，看的人不用自己判断。
 * 关卡是**做题**：玩家自己走，走错了要重来，走对了才往下走。
 *
 * 所以关卡不能复用课程的 `Lesson`：
 *   - 课程要 `note`（讲解），关卡**不能**有 —— 提示是「点一下才给」的那一着，
 *     不是摆在旁边的答案；
 *   - 课程是**线性播放**，关卡是**交互判定**；
 *   - 课程的局面由着法推导，关卡的局面**就是一个给定局面**（残局本来就是给定的）。
 *
 * ## 解法线是**固化**的，判定不依赖引擎
 *
 * 一关存的是一条走通的着法序列（玩家着法与对手应手交替）。
 * 玩家走错 → 判定为错，不推进；走对 → 推进到下一 ply。
 * 整条线走完 = 通关。
 *
 * 为什么不靠引擎实时判定：
 *   - 浏览器里没有引擎（引擎在服务端，且分析一次要秒级）；
 *   - 实时判定会**每次都算出不一样的结果**（引擎版本一变，难度就变了）；
 *   - 固化的线让每关的难度**可复现** —— 同一个关卡永远是同一道题。
 *
 * 引擎只在**离线生成题库**时用（见 `scripts/generate-endgame-puzzles.ts`）。
 */
import type { Color } from '../../types';

/**
 * **关卡目标** —— 玩家在这关要达成什么。
 *
 * 四种都要，因为残局教学里「守和」和「取胜」同样重要：
 * 只教取胜，就砍掉了一半的残局内容。
 */
export type PuzzleGoal =
  /** N 手内将死对手 */
  | 'mate'
  /** 取胜（将死或靠子力赢下来） */
  | 'win'
  /** 守和（把必败的局面扳成和棋） */
  | 'draw'
  /** 把兵推到底线升变取胜 */
  | 'promote';

/** 关卡里的一手 */
export interface PuzzlePly {
  /** 这一手是谁走的 */
  color: Color;
  /** 标准记谱（SAN） */
  san: string;
  /** 起点格 */
  from: string;
  /** 终点格 */
  to: string;
  /** 走完这手之后的局面 */
  fen: string;
  /**
   * 玩家这一手还有哪些**等价正解**（SAN）。
   *
   * 为什么要有：很多残局是**多解都成立**的 —— 把「只有一着对」当成唯一标准，
   * 会把好题误判成坏题。走 `also` 里的着法也算走对。
   *
   * 对手着法**没有**这个字段：对手怎么应是**唯一**的（离线时按引擎最优着法固化），
   * 不给玩家「对手这一步其实可以随便走」的自由度。
   */
  also?: string[];
  /**
   * **对手这一手的解说**（只有对手的着法才有）。
   *
   * 存在的理由：残局里对手已败时，它的「最优应手」往往就是
   * **看着像白送、其实能把杀棋拖最久**的那手 ——
   * 不解释的话，玩家会以为对手在犯傻（「白白将杀」）。
   *
   * 这一份数据是**离线**用引擎算好的（见 `scripts/generate-endgame-puzzles.ts`），
   * 运行时**不碰引擎** —— 跟走法线一样是固化的。
   */
  note?: PuzzleOpponentNote;
}

/**
 * **对手这一手的解说** —— 为什么对手这么走。
 *
 * ## 这里面存的是什么
 *
 * 不是一句写好的话，而是**几个可以组合出话的事实**：
 * 局面性质（必败/还在拉锯）、着法性质（唯一合法/最优/牺牲换时间）、
 * 以及**跟其它着法比**的结果（拖了几手、差了多少分）。
 *
 * 为什么要存事实而不是直接存成句的中文：
 * 同样的事实可以拼出不同的说法（「唯一合法」比「对手没得选」更准确），
 * 而且文案改了不用重新跑引擎 —— 引擎是离线最贵的一步。
 */
export interface PuzzleOpponentNote {
  /**
   * 对手在这个局面**有几手合法着法**。
   *
   * = 1 时就是「唯一合法着法」—— 对手没有选择余地。
   */
  legalCount: number;
  /**
   * 对手在这个局面**是不是已经守不住了**（引擎判定）。
   *
   * 两种「守不住」都算：
   *   - **被杀棋** —— 几手内就要死（`mateInAfter` 不为 null）；
   *   - **子力层面已败** —— 没有强制杀，但分值大劣，输定了。
   *
   * 这一条是解说的关键：必败局面下的最优应手 = 拖延 / 少输，
   * 看起来就像在送 —— 有了这一条才说得清「它不是在犯傻」。
   */
  hopeless: boolean;
  /**
   * 这一手在引擎眼里是**最优**（与最佳着法等价）。
   *
   * 假值说明这手不是最优 —— 那就要老实告诉玩家「这手有更好的选择」。
   */
  isBest: boolean;
  /**
   * 走完这手之后，玩家**几步能杀**（手）；不是杀棋局面时为 null。
   *
   * 对手已败时，这个数越大 = 拖得越久。
   */
  mateInAfter: number | null;
  /**
   * 走完这手之后，**局面分值**（对手视角，厘兵）。
   *
   * 对手视角：负数越大 = 对手越惨。
   */
  scoreAfter: number | null;
  /**
   * 引擎给这个局面的**最佳着法**（SAN）。
   *
   * 跟实际这手不同时才有意义 —— 用来告诉玩家「更好的选择是什么」。
   */
  bestSan: string | null;
  /**
   * 引擎的最佳着法走完之后，局面分值（对手视角，厘兵）。
   *
   * 跟 `scoreAfter` 一比，就知道这手差了多少。
   */
  bestScoreAfter: number | null;
  /**
   * 引擎的最佳着法走完之后，玩家几步能杀（手）。
   *
   * 跟 `mateInAfter` 一比，就知道这手少拖了几手。
   */
  bestMateInAfter: number | null;
  /**
   * 这一手**牺牲了子力**（对手掉了多少子力，单位：厘兵）。
   *
   * 「弃子换时间」是残局里最容易被误解的一手 ——
   * 看着像白送，其实是拿子换步数。不解释的话玩家一定会觉得对手在犯傻。
   */
  sacrificedCp: number;
}

/**
 * **「对手已经守不住了」的子力门槛**（对手视角，厘兵）。
 *
 * 对手走完这一手之后仍然落后这么多 = 输定了。
 *
 * 取 500（约一个后）—— 不是「占优」的程度，是「输定」的程度。
 */
export const HOPELESS_SCORE_CP = -500;

/**
 * 判断对手在**走完这一手之后**是不是已经守不住了。
 *
 * ## 为什么这个判定要有一份**共享**的实现
 *
 * 离线生成器（`scripts/generate-endgame-puzzles.ts`）算这个标志，
 * 单测又要把数据里的标志跟事实对一遍 ——
 * 两边各写一套的话，迟早会写出**不一样**的两套，
 * 然后单测拿着生成器自己的错当标准，测了个寂寞。
 *
 * 所以判定规则只写这一份，生成器与单测都调它。
 *
 * ## 两个事实都是「对手视角」
 *
 * - `mateInAfter` —— 走完这手之后玩家几步能杀（对手被杀），不是 null 就是被将死；
 * - `scoreAfter` —— 走完这手之后的局面分值，**对手视角**：
 *   负数 = 对手落后，负得越多越惨。
 */
export function isOpponentHopeless(facts: {
  mateInAfter: number | null;
  scoreAfter: number | null;
}): boolean {
  // 被杀棋 = 无解
  if (facts.mateInAfter !== null) return true;
  // 子力大劣 = 输定
  return facts.scoreAfter !== null && facts.scoreAfter <= HOPELESS_SCORE_CP;
}

/** 一关的出处 */
export interface PuzzleSource {
  /** 来源名（如题库名） */
  name: string;
  /** 来源链接 */
  url?: string;
  /** 授权（如 CC0） */
  license?: string;
}

/** 一关 */
export interface Puzzle {
  /** 稳定 id（用于存档与深链） */
  id: string;
  /** 中文名 */
  name: string;
  /** 英文名 / 别名 */
  en: string;
  /**
   * 主题键（对应 `themes.ts` 里的表）。
   *
   * 用**键**而不是直接存中文：中文标签会改，键不会 ——
   * 存档里存的是 id，不是名字。
   */
  theme: string;
  /** 难度 1~5 */
  difficulty: 1 | 2 | 3 | 4 | 5;
  /** 起始局面（**轮到玩家走**） */
  fen: string;
  /** 玩家执子 */
  side: Color;
  /** 目标 */
  goal: PuzzleGoal;
  /** `goal = 'mate'` 时的杀棋手数 */
  mateIn?: number;
  /** 主线（玩家着法与对手应手交替，从玩家那手开始） */
  line: PuzzlePly[];
  /** 通关后显示的要点 */
  points: string[];
  /** 出处 */
  source: PuzzleSource;
}

